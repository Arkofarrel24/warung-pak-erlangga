/**
 * A time-varying arrival rate: the profile λ(t) itself, and the arrivals the
 * engine generates from it by thinning.
 */

import assert from 'node:assert/strict';
import test from 'node:test';

import { ArrivalProfile } from '../src/sim/arrival-profile.js';
import { EVENT, QueueSimulation } from '../src/sim/engine.js';

function assertClose(actual, expected, tolerance = 1e-12, label = '') {
  assert.ok(
    Math.abs(actual - expected) <= tolerance,
    `${label} expected ${expected}, got ${actual}`,
  );
}

// ---------------------------------------------------------------------------
// The profile
// ---------------------------------------------------------------------------

/** Quiet, a climb to a lunch peak, a slow decline, then flat. */
const DAY = [
  { time: 0, rate: 5 },
  { time: 2, rate: 5 },
  { time: 4, rate: 40 },
  { time: 5, rate: 40 },
  { time: 8, rate: 10 },
  { time: 12, rate: 10 },
];

/**
 * Expected arrivals in each hour of DAY, worked out by hand as the area of
 * a trapezoid. On the climb λ rises by 17.5 per hour, on the decline it
 * falls by 10 per hour.
 */
const DAY_HOURLY = [
  5, //                    0-1   flat at 5
  5, //                    1-2
  (5 + 22.5) / 2, //       2-3   5 -> 22.5
  (22.5 + 40) / 2, //      3-4   22.5 -> 40
  40, //                   4-5   flat at 40
  (40 + 30) / 2, //        5-6   40 -> 30
  (30 + 20) / 2, //        6-7
  (20 + 10) / 2, //        7-8
  10, //                   8-9   flat at 10
  10,
  10,
  10,
];
const DAY_TOTAL = 210;

test('the rate is interpolated in a straight line between points', () => {
  const profile = new ArrivalProfile(DAY);

  assert.equal(profile.rateAt(0), 5);
  assert.equal(profile.rateAt(1.3), 5);
  assertClose(profile.rateAt(3), 22.5);
  assertClose(profile.rateAt(3.5), 31.25);
  assert.equal(profile.rateAt(4), 40);
  assertClose(profile.rateAt(6.5), 25);
  assert.equal(profile.rateAt(8), 10);
});

test('outside its points the rate stays flat', () => {
  const profile = new ArrivalProfile([
    { time: 2, rate: 6 },
    { time: 4, rate: 10 },
  ]);

  assert.equal(profile.rateAt(0), 6);
  assert.equal(profile.rateAt(100), 10);
  assert.equal(profile.rateBefore(0), 6);
  assert.equal(profile.rateBefore(100), 10);
});

test('a single point is a constant rate', () => {
  const profile = new ArrivalProfile([{ time: 0, rate: 8 }]);

  assert.equal(profile.rateAt(0), 8);
  assert.equal(profile.rateAt(7.7), 8);
  assert.equal(profile.maxRate, 8);
  assertClose(profile.expectedArrivals(1, 4), 24);
});

test('two points at the same time make a jump', () => {
  const profile = new ArrivalProfile([
    { time: 0, rate: 4 },
    { time: 3, rate: 4 },
    { time: 3, rate: 20 },
    { time: 6, rate: 20 },
  ]);

  assert.equal(profile.rateAt(2.999), 4);
  assert.equal(profile.rateBefore(3), 4, 'just before the jump');
  assert.equal(profile.rateAt(3), 20, 'at the jump the new rate applies');
  assert.equal(profile.rateAt(3.001), 20);
  // 3 hours at 4 plus 3 hours at 20
  assertClose(profile.expectedArrivals(0, 6), 72);
  assertClose(profile.expectedArrivals(2, 4), 24);
});

test('the highest rate is found at one of the points', () => {
  assert.equal(new ArrivalProfile(DAY).maxRate, 40);
});

test('expected arrivals match the trapezoid areas worked out by hand', () => {
  const profile = new ArrivalProfile(DAY);

  DAY_HOURLY.forEach((expected, hour) => {
    assertClose(profile.expectedArrivals(hour, hour + 1), expected, 1e-12, `hour ${hour}`);
  });
  assertClose(profile.expectedArrivals(0, 12), DAY_TOTAL);
  // An interval that starts and ends in the middle of a slope: λ(2.5) = 13.75
  // and λ(3.5) = 31.25, so the area is one hour at their average.
  assertClose(profile.expectedArrivals(2.5, 3.5), 22.5);
  assert.equal(profile.expectedArrivals(5, 5), 0);
  assert.equal(profile.expectedArrivals(6, 5), 0);
});

test('an invalid profile is rejected', () => {
  const invalid = [
    [],
    'not a list',
    [{ time: 0, rate: -1 }],
    [{ time: 0, rate: Number.NaN }],
    [{ time: Infinity, rate: 5 }],
    // Out of order
    [
      { time: 2, rate: 5 },
      { time: 1, rate: 5 },
    ],
    // Nobody ever arrives
    [
      { time: 0, rate: 0 },
      { time: 5, rate: 0 },
    ],
  ];
  for (const points of invalid) {
    assert.throws(() => new ArrivalProfile(points), RangeError, JSON.stringify(points));
  }
});

// ---------------------------------------------------------------------------
// Arrivals generated by the engine
// ---------------------------------------------------------------------------

test('a flat profile gives exactly the arrivals of a constant rate', () => {
  // With λ(t) = λ_max everywhere, thinning keeps every candidate, so the
  // arrival times must be the same numbers, not just the same on average.
  const shared = { serviceRate: 10, servers: 2, capacity: 6, duration: 300, warmup: 20, seed: 19 };
  const constant = new QueueSimulation({ ...shared, arrivalRate: 14 }).run();
  const flat = new QueueSimulation({
    ...shared,
    arrivalProfile: [
      { time: 0, rate: 14 },
      { time: 100, rate: 14 },
    ],
  }).run();

  assert.deepEqual(flat, constant);
});

test('no customer arrives while the rate is zero', () => {
  const simulation = new QueueSimulation({
    arrivalProfile: [
      { time: 0, rate: 20 },
      { time: 3, rate: 20 },
      { time: 3, rate: 0 },
      { time: 6, rate: 0 },
      { time: 6, rate: 20 },
    ],
    serviceRate: 30,
    duration: 9,
    seed: 5,
  });
  const arrivalTimes = [];
  for (let event = simulation.step(); event; event = simulation.step()) {
    if (event.type === EVENT.ARRIVAL) arrivalTimes.push(event.time);
  }

  assert.ok(arrivalTimes.some((time) => time < 3));
  assert.ok(arrivalTimes.some((time) => time > 6));
  assert.ok(!arrivalTimes.some((time) => time >= 3 && time < 6), 'the gap stays empty');
});

/**
 * The statistical test of thinning. What defines a non-homogeneous Poisson
 * process is that the number of arrivals in an interval is Poisson
 * distributed with mean Λ = ∫ λ(t) dt, and that disjoint intervals are
 * independent. So over many simulated days, for every hour:
 *
 *   - the mean count must equal Λ of that hour (within 4 standard errors),
 *   - the variance must equal the mean, the fingerprint of a Poisson
 *     distribution (index of dispersion = variance / mean = 1),
 *   - counts of neighboring hours must be uncorrelated.
 *
 * The shortcut "draw the next gap from the current rate" fails the first
 * check: it puts too few arrivals in the hours where λ is climbing.
 */
test('thinning produces a Poisson process with rate λ(t)', () => {
  const DAYS = 5000;
  const HOURS = DAY_HOURLY.length;
  const counts = Array.from({ length: HOURS }, () => new Float64Array(DAYS));
  const totals = new Float64Array(DAYS);

  for (let day = 0; day < DAYS; day++) {
    const results = new QueueSimulation({
      arrivalProfile: DAY,
      // Service is made nearly instant; only the arrivals matter here.
      serviceRate: 1000,
      servers: 5,
      closingTime: 12,
      periodLength: 1,
      seed: 2026,
      replication: day,
    }).run();
    for (let hour = 0; hour < HOURS; hour++) counts[hour][day] = results.periods[hour].arrivals;
    totals[day] = results.arrivals;
  }

  const mean = (values) => values.reduce((sum, x) => sum + x, 0) / values.length;
  const variance = (values, m) =>
    values.reduce((sum, x) => sum + (x - m) ** 2, 0) / (values.length - 1);

  for (let hour = 0; hour < HOURS; hour++) {
    const expected = DAY_HOURLY[hour];
    const m = mean(counts[hour]);
    const v = variance(counts[hour], m);
    const standardErrors = Math.abs(m - expected) / Math.sqrt(v / DAYS);

    assert.ok(
      standardErrors < 4,
      `hour ${hour}: expected ${expected} arrivals, got ${m} (${standardErrors.toFixed(1)} standard errors)`,
    );
    // With 5,000 days the dispersion index of a true Poisson count has a
    // standard deviation of about 0.021, so 0.1 is more than 4 of them.
    assert.ok(Math.abs(v / m - 1) < 0.1, `hour ${hour}: index of dispersion ${v / m}`);
  }

  const totalMean = mean(totals);
  const totalVariance = variance(totals, totalMean);
  assert.ok(Math.abs(totalMean - DAY_TOTAL) / Math.sqrt(totalVariance / DAYS) < 4, `total ${totalMean}`);
  assert.ok(Math.abs(totalVariance / totalMean - 1) < 0.1, 'the daily total is Poisson too');

  // Independent increments: a correlation estimated from n independent pairs
  // has a standard deviation of about 1/√n.
  for (let hour = 1; hour < HOURS; hour++) {
    const a = counts[hour - 1];
    const b = counts[hour];
    const meanA = mean(a);
    const meanB = mean(b);
    let covariance = 0;
    for (let day = 0; day < DAYS; day++) covariance += (a[day] - meanA) * (b[day] - meanB);
    covariance /= DAYS - 1;
    const correlation = covariance / Math.sqrt(variance(a, meanA) * variance(b, meanB));
    assert.ok(
      Math.abs(correlation) < 4 / Math.sqrt(DAYS),
      `hours ${hour - 1} and ${hour}: correlation ${correlation}`,
    );
  }
});

test('the arrival rate is given either as a number or as a profile', () => {
  const base = { serviceRate: 10, duration: 100 };

  assert.throws(() => new QueueSimulation(base), RangeError, 'neither');
  assert.throws(
    () => new QueueSimulation({ ...base, arrivalRate: 8, arrivalProfile: DAY }),
    RangeError,
    'both',
  );
  assert.throws(
    () => new QueueSimulation({ ...base, arrivalProfile: [{ time: 0, rate: -3 }] }),
    RangeError,
  );
  assert.doesNotThrow(() => new QueueSimulation({ ...base, arrivalProfile: DAY }));
});
